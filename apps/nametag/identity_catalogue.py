"""The background catalogue: 50 frozen ids, 38 procedural and 12 glyph.

GENERATED by `setup/host/generate_catalogue.py`.  Do not hand-edit: the
generator reads `namebadge/badge/namebadge/skins.py` and the harvested `.gpd`
streams for WHICH backgrounds exist, `setup/host/catalogue/order.json` for
WHAT ORDER they appear in, and a test re-runs it and diffs this file.

THE ORDER IS THE OWNER'S, DECLARED IN A FILE (2026-08-27).  It is not source
order, not glob order, and not sortable from anything in this module: entries
1-12 are the glyph decks and the rest are procedural skins, interleaved on
taste.  Two consequences a reader will otherwise trip over.  GROUPS ARE LABELS,
NOT BLOCKS -- `RETRO` and `PLAY` each appear in two separate runs because the
owner's sequence puts them there, so nothing may assume a group is one
contiguous stretch of `ENTRIES`.  And `GROUPS` lists only groups that HAVE
members; `skins.GROUPS` still carries the empty ones, because its positions are
indexed by every `SKINS` row.

AN ID IS A STRING AND IS FROZEN FOREVER.  Setup persists that id, never this
table's position, so presentation order may change without re-skinning a saved
badge. Every id is derived from the artwork's own name and pinned by a golden
test, so a rename is visible. Procedural rendering goes through `skin_index()`;
using `index_of()` as a `skins.py` index is a defect whenever glyphs interleave.

AN UNKNOWN ID IS KEPT, NOT DISCARDED.  `identity_model.repair` does not consult
this table at all: a background id it has never heard of survives a save
untouched, renders as the default, and starts working again the moment the asset
is reinstalled.  A badge configured on a newer build therefore degrades to
"wrong picture" rather than to "your badge is gone".

Pure data plus linear lookups.  No dict index is built: 50 entries are scanned
in microseconds a handful of times per screen, and a parallel dict would double
the resident cost of the table for no measurable gain.
"""


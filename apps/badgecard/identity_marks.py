COUNT = len(MARKS)


def index_of(mark_id):
    """Position in MARKS, or -1.  Never raises, whatever it is handed."""
    for index in range(len(MARKS)):
        if MARKS[index][0] == mark_id:
            return index
    return -1


def get(mark_id):
    """The whole tuple, or None for an id this build does not ship."""
    index = index_of(mark_id)
    return MARKS[index] if index >= 0 else None


def known(mark_id):
    return index_of(mark_id) >= 0


def label(mark_id):
    """The wearer-facing name, or the id itself if we do not know it.

    Falling back to the id rather than to a placeholder is the catalogue's own
    rule: an unknown mark keeps its string in state so reinstalling the sheet
    restores the badge, and showing that string is how someone finds out WHICH
    mark is missing.
    """
    mark = get(mark_id)
    return mark[1] if mark is not None else mark_id


def ids():
    return tuple(mark[0] for mark in MARKS)


def cell(index, now_ms=0):
    """The sheet cell for mark `index` at `now_ms`.  Integer-only, stateless.

    A static mark ignores the clock entirely.  An animated one is offset by its
    own index so several animated marks on one badge do not beat in unison --
    `namebadge`'s rule, and the reason is visual: four marks flipping together
    reads as the screen refreshing rather than as four independent things.

    Stateless so the same elapsed time always gives the same cell: a dropped
    frame is skipped rather than accumulated, and two badges started together
    stay in step.  The caller passes 0 to freeze the animation, which is what
    `motion` off means.
    """
    if index < 0 or index >= len(MARKS):
        return -1
    first, frames = MARKS[index][2], MARKS[index][3]
    if frames > 1:
        first += (now_ms // FRAME_MS + index * 3) % frames
    return first

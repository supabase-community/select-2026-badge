COUNT = len(ENTRIES)


def index_of(entry_id):
    """Position in ENTRIES, or -1.  Never raises, whatever it is handed."""
    for index in range(len(ENTRIES)):
        if ENTRIES[index][0] == entry_id:
            return index
    return -1


def label(entry_id):
    """The wearer-facing name, or the id itself if we do not know it.

    Falling back to the id rather than to a placeholder is deliberate: an
    unknown background keeps its string in state so reinstalling the asset
    restores the badge, and showing that string is how someone finds out WHICH
    asset is missing.
    """
    return LABELS.get(entry_id, entry_id)


def known(entry_id):
    return index_of(entry_id) >= 0


def get(entry_id):
    """The whole entry tuple, or None for an id this build does not ship."""
    index = index_of(entry_id)
    return ENTRIES[index] if index >= 0 else None


def group_of(entry_id, fallback=""):
    entry = get(entry_id)
    return entry[1] if entry is not None else fallback


def kind_of(entry_id, fallback=""):
    entry = get(entry_id)
    return entry[2] if entry is not None else fallback


def ids():
    return tuple(entry[0] for entry in ENTRIES)


def in_group(group):
    return tuple(entry[0] for entry in ENTRIES if entry[1] == group)


def first_of_group(group):
    for entry in ENTRIES:
        if entry[1] == group:
            return entry[0]
    return ENTRIES[0][0]


def next_group(group, step=1):
    """The group `step` places along, wrapping.  An unknown group starts over."""
    if group in GROUPS:
        index = GROUPS.index(group)
    else:
        index = -1 if step > 0 else 0
    return GROUPS[(index + step) % len(GROUPS)]

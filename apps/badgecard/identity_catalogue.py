"""The background catalogue: 106 frozen ids, 88 procedural and 18 glyph.

GENERATED by `badgecard/host/generate_catalogue.py`.  Do not hand-edit: the
generator reads `namebadge/badge/namebadge/skins.py` and the harvested `.gpd`
streams, and a test re-runs it and diffs this file.

AN ID IS A STRING AND IS FROZEN FOREVER.  `profile` and `namebadge` persist
`skin: <int>`, an index into a tuple, so inserting one entry rewrites every
wearer's badge and the catalogue can never be improved in the middle.  Every id
here is derived from the artwork's own name and pinned by a golden test, so new
artwork is always additive and a rename is a visible test failure.

AN UNKNOWN ID IS KEPT, NOT DISCARDED.  `identity_model.repair` does not consult
this table at all: a background id it has never heard of survives a save
untouched, renders as the default, and starts working again the moment the asset
is reinstalled.  A badge configured on a newer build therefore degrades to
"wrong picture" rather than to "your badge is gone".

Pure data plus linear lookups.  No dict index is built: 76 entries are scanned in
microseconds a handful of times per screen, and a parallel dict would double the
resident cost of the table for no measurable gain.
"""


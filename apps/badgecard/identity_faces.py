"""The ROM face ladder: 37 typefaces, measured, in the pinned runtime.

GENERATED by `node identity/host/measure_faces.mjs`.  Do not hand-edit; a test
re-runs the generator's numbers against this file.

WHY THE NUMBERS ARE HERE AND NOT TAKEN AT DRAW TIME.  `font.<name>` opens
/rom/fonts/<name>.ppf, so measuring a face on the badge is a filesystem read.
The typeface screen needs every visible face's HEIGHT before it can place a
single row, and the poster needs a face's WIDEST GLYPH before it commits to
drawing a name in it.  Both are constants of the firmware, so they are measured
once on the host and shipped as data.

WIDEST is the widest single advance over exactly the glyphs
`identity_keyboard.ROWS` can produce -- A-Z, 0-9, space and `- . & '`.  That is
the set that matters, because the number has one job: proving a name the wearer
can actually TYPE cannot run off the canvas.  `widest * len(name) <= budget` is
a sufficient condition for any string over that alphabet, whatever the glyphs.

CAP is `measure_text("A")[1]`, the LINE BOX height -- the same quantity
`ui.Chrome.text_h` reads for the chrome face.  A row sized from it cannot clip
the glyphs it carries.  The faces run from 10 px (`desert`) to 30 px (`more`),
which is why the typeface list has ragged rows: a uniform row either clips the
tall faces or fits three of them on a 107 px content area.

`namebadge.skins.FONT_WIDEST` measures the same quantity over ITS keyboards'
glyph set and disagrees on four faces (`absolute`, `ark`, `manticore`,
`nope`).  Neither table is wrong; they are answers to two different questions,
and `test_identity_faces` pins the difference so it cannot drift into a
surprise.

Pure data plus linear lookups, like `identity_catalogue`: 37 entries scanned a
handful of times per screen cost microseconds, and a parallel dict would double
the resident cost of the table for nothing.
"""


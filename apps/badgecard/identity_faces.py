# The narrowest face there is.  The poster's guaranteed fallback: any name of
# `n` characters measures at most `WIDEST_MIN * n`, so a budget that clears that
# clears every string the keyboard can produce.
WIDEST_MIN = min(entry[1] for entry in FACES)

# The pessimistic answers, used for a face this build has never heard of.  An
# unknown `state["face"]` is KEPT rather than discarded (schema rule 2), so the
# view will ask about it, and every caller asks in order to decide whether
# something FITS -- where an optimistic guess is a name drawn off the canvas.
WIDEST_MAX = max(entry[1] for entry in FACES)
CAP_MAX = max(entry[2] for entry in FACES)


def _row(face_id):
    for index in range(len(FACES)):
        if FACES[index][0] == face_id:
            return FACES[index]
    return None


def known(face_id):
    return _row(face_id) is not None


def widest(face_id, fallback=WIDEST_MAX):
    """The widest advance, or `fallback` for a face this ROM does not carry."""
    entry = _row(face_id)
    return entry[1] if entry is not None else fallback


def cap(face_id, fallback=CAP_MAX):
    entry = _row(face_id)
    return entry[2] if entry is not None else fallback


def fits(face_id, length, budget):
    """Can `length` characters of ANY typeable string fit `budget` px?

    A sufficient condition, not an exact measurement: it multiplies the widest
    glyph, so a name of narrow letters that this refuses would in fact have fit.
    That is the right direction to be wrong in -- the alternative is measuring
    the actual string, which means opening the font.
    """
    return widest(face_id) * length <= budget


def ladder():
    """Every face id, narrowest first, then shortest.

    The order a fallback walks: the first entry is the face most likely to hold
    a long name, and `FACES` order (alphabetical) is what the picker shows.
    """
    return tuple(entry[0] for entry in
                 sorted(FACES, key=lambda entry: (entry[1], entry[2], entry[0])))


def ids():
    return tuple(entry[0] for entry in FACES)
